const { chromium } = require('playwright');
const fs = require('fs');
const script = fs.readFileSync(process.argv[2], 'utf8');
const series = ['Witch on the Holy Night', 'YuruYuri', 'Petite serie', 'Grande serie incomplete', 'Grande serie complete'];
const sizes = { 'Witch on the Holy Night': 6, 'YuruYuri': 5, 'Petite serie': 3, 'Grande serie incomplete': 6, 'Grande serie complete': 7 };
const characters = []; let id = 0;
for (const s of series) for (let i = 0; i < sizes[s]; i++) characters.push({ id: id++, name: `${s} ${i}`, rarity: 'R', series: s, image: '' });
const collection = characters.filter((c) => !(c.series === 'Grande serie incomplete' && c.name.endsWith(' 0')) && !(c.series === 'YuruYuri' && c.name.endsWith(' 1'))).map((c) => ({ characterId: c.id, qty: 1, listable: 1 }));
const progress = { now: new Date().toISOString(), series: [{ series: 'Witch on the Holy Night', size: 6, chakra: 50, completedAt: '2026-11-04T20:18:47.244Z', claimed: true }, { series: 'YuruYuri', size: 5, chakra: 50, completedAt: '2026-10-31T17:37:38.552Z', claimed: true }] };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('https://kyara.games/**', async (route) => {
    const url = new URL(route.request().url()); const p = url.pathname;
    const json = (body) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) });
    if (p === '/api/characters') return json(characters);
    if (p === '/api/me/bootstrap') return json({ me: { id: 'me' }, wishlist: [] });
    if (p === '/api/me/collection') return json(collection);
    if (p === '/api/me/progress') return json(progress);
    if (p.startsWith('/api/')) return json({});
    if (p === '/collection') return route.fulfill({ status: 200, contentType: 'text/html', body: `<!doctype html><html><body><main><div class="al-tools"></div><ul class="albums">${series.map((s, i) => i % 2 ? `<li><button class="album"><span class="a-name">${s}</span></button></li>` : `<li class="al"><span class="al-name">${s}</span></li>`).join('')}</ul></main></body></html>` });
    if (p === '/missions') return route.fulfill({ status: 200, contentType: 'text/html', body: `<!doctype html><html><body><main><section id="mi-albums" aria-labelledby="albums-t"><header><h2 id="albums-t">Séries complètes</h2></header><div class="al-list"><ul class="albums claimed-list"><li class="al claimed"><span class="al-name">Witch on the Holy Night</span></li></ul></div><button class="fold">Voir les 1 séries réclamées</button></section></main></body></html>` });
    return route.fulfill({ status: 404, body: '' });
  });
  await page.addInitScript(() => { localStorage.setItem('kyara_token', 'fake'); });
  await page.goto('https://kyara.games/collection');
  await page.addScriptTag({ content: script });
  await page.waitForTimeout(1500);
  const out = {};
  out.collection = await page.evaluate(() => [...document.querySelectorAll('main ul.albums > li')].map((li) => (li.querySelector('.a-name, .al-name').textContent + ' => ' + (li.querySelector('.kp-claim')?.textContent ?? '—') + ' [' + (li.querySelector('.kp-claim')?.title ?? '') + ']')));
  const visible = () => page.evaluate(() => [...document.querySelectorAll('main ul.albums > li')].filter((li) => !li.classList.contains('kp-filtered-out')).map((li) => li.querySelector('.a-name, .al-name').textContent));
  out.visibleBefore = await visible();
  await page.click('.kp-album-filters .kp-chip:has-text("Masquer les déjà réclamées")'); await page.waitForTimeout(150);
  out.visibleHidden = await visible();
  out.pressed = await page.getAttribute('.kp-album-filters .kp-chip:has-text("Masquer")', 'aria-pressed');
  out.stored = await page.evaluate(() => JSON.parse(localStorage.getItem('kyara-plus:settings')).albumHideClaimed);
  await page.click('.kp-album-filters .kp-chip:has-text("Masquer les déjà réclamées")'); await page.waitForTimeout(150);
  out.visibleRestored = await visible();
  await page.goto('https://kyara.games/missions');
  await page.addScriptTag({ content: script });
  await page.waitForTimeout(600);
  out.missionsScriptToggle = await page.evaluate(() => document.querySelector('.kp-series-toggle') !== null);
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})();
